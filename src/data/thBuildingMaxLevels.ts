export function getMaxBuildingLevel(defenseId: string, thLevel: TownHallLevel): number {
  const defense = DEFENSES[defenseId];
  if (!defense) return 0;
  if (thLevel < defense.unlockedAtTH) return 0;
  const mapping = TH_BUILDING_MAX[defenseId];
  if (mapping && mapping[thLevel] !== undefined) {
    return mapping[thLevel]!;
  }
  if (mapping) {
    for (let th = thLevel - 1; th >= defense.unlockedAtTH; th--) {
      if (mapping[th as TownHallLevel] !== undefined) {
        return mapping[th as TownHallLevel]!;
      }
    }
  }
  return 0;
}

export const getMaxLevelForTH = getMaxBuildingLevel;
